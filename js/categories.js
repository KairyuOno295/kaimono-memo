let index = null;

function buildIndex() {
  index = [];
  for (const [cat, words] of Object.entries(KEYWORDS)) {
    for (const w of words) index.push([nameKey(w), cat]);
  }
  // 長いことばを先に見る（「アイスコーヒー」は「アイス」より「コーヒー」を優先…のように、より長く一致した方）
  index.sort((a, b) => b[0].length - a[0].length);
}

/** 品目名からカテゴリを推測する。わからなければ ''（＝その他） */
export function guessCategory(name) {
  if (!index) buildIndex();
  const key = nameKey(name);
  if (!key) return '';
  const hit = index.find(([w]) => key.includes(w));
  return hit ? hit[1] : '';
}

/** 表示する順のカテゴリ一覧（最初からのもの → 追加したもの → 最後に「その他」） */
export function allCategories(custom = []) {
  const extra = [...custom].sort(byPosition).map((c) => ({ ...c, custom: true }));
  const base = DEFAULT_CATEGORIES.filter((c) => c.id !== FALLBACK_CATEGORY);
  const other = DEFAULT_CATEGORIES.find((c) => c.id === FALLBACK_CATEGORY);
  return [...base, ...extra, other];
}
